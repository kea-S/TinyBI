import json
import os

import instructor
from openai import AsyncOpenAI
from ragas.metrics.collections import FactualCorrectness
from ragas.llms import InstructorLLM


def _get_scorer_llm():
    model = os.environ.get("RAGAS_SCORER_MODEL", "ibm-granite/granite-4.1-3b")
    use_vllm = os.environ.get("TINYBI_USE_VLLM", "false").lower() == "true"
    if use_vllm:
        base_url = os.environ.get("TINYBI_VLLM_URL", "http://host.docker.internal:8001/v1")
        api_key = "none"
    else:
        ollama_url = os.environ.get("OLLAMA_HOST", "http://localhost:11434")
        base_url = f"{ollama_url}/v1"
        api_key = "ollama"
    client = instructor.from_openai(
        AsyncOpenAI(base_url=base_url, api_key=api_key)
    )
    return InstructorLLM(client=client, model=model, provider="openai")


def insight_scorer(output: str, context: dict) -> dict:
    """
    Promptfoo assertion that scores the agent's natural-language answer
    against a pre-computed reference answer using RAGAS FactualCorrectness.

    The reference_answer is read directly from the test's vars (committed
    in tests.yaml), not from a runtime cache.

    Caveat: Reference answers are pre-generated by the gold cache pipeline.
    Quality depends on the gold model's ability to summarize oracle data.
    If references are flawed, scores are meaningless.
    """
    vars_ = context.get("vars", {})

    reference_answer = vars_.get("reference_answer")
    if not reference_answer:
        raise KeyError(
            "reference_answer not found in vars. "
            "Each test must have a pre-computed reference_answer."
        )

    try:
        result = json.loads(output)
        agent_answer = result.get("output", output)
    except (json.JSONDecodeError, AttributeError):
        agent_answer = output

    llm = _get_scorer_llm()
    metric = FactualCorrectness(llm=llm, mode="f1", beta=1.0)
    ragas_result = metric.score(response=agent_answer, reference=reference_answer)
    score = ragas_result.value
    rounded = round(score, 2)

    return {
        "pass": True,
        "score": rounded,
        "named_scores": {"RAGAS F1": rounded},
        "reason": f"Score: {score:.2f} | Reference: {reference_answer[:120]}{'...' if len(reference_answer) > 120 else ''}",
    }
